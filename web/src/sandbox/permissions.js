/**
 * Что разрешено в песочнице.
 *
 * Песочница живёт не только на своей странице: урок вставляет её в текст, и там она обычно
 * должна быть строже — программу правят у одного процессора, строить нельзя, время не
 * перематывают. Игрового понятия для этого нет: игра ничего не запрещает игроку, — поэтому
 * набор наш, и он один на все места, где песочницу встраивают.
 *
 * Всё по умолчанию разрешено: страница песочницы ничего не передаёт и работает как раньше.
 */

/** Полный набор с умолчаниями. */
export const FULL = {
    /** Каким процессорам можно править программу: `true`, `false` или список имён связей */
    edit: true,

    /** Какие инструкции показывает меню добавления: `true` или список опкодов */
    instructions: true,

    /** Панель строительства, постановка блока и снос */
    build: true,

    /** Пауза, шаг, перемотка и скорость времени */
    time: true,

    /** Кнопка сброса мира */
    reset: true,

    /** Игровой HUD и кнопка его скрытия */
    hud: true,

    /** Щелчки по миру: тумблер, дверь, ряд настройки блока */
    interact: true
}

/** Дополняет переданное умолчаниями. */
export function permissions(allow = {}) {
    return {...FULL, ...allow}
}

/**
 * Можно ли править программу этого процессора. Список задаётся именами связей — теми же,
 * что видит программа: `processor1`, `micro-processor1`.
 */
export function canEdit(allow, building) {
    if (allow.edit === true) return true
    if (allow.edit === false || building === null || building === undefined) return false

    return Array.isArray(allow.edit) && allow.edit.includes(building.name)
}
