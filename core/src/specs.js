/**
 * Спеки блоков и юнитов — развёрнутые из сжатой выгрузки.
 *
 * Выгрузка из игры держит у каждого блока полсотни полей, и большая часть из них у всех
 * одинакова: `false`, пустой список, значение по умолчанию. Файл при этом весил полмегабайта,
 * и весь он уезжал в браузер вместе с примером. Поэтому `gen-dump.mjs` пишет его сжатым:
 * отдельно значения по умолчанию, отдельно у каждого блока только то, чем он от них
 * отличается. Разворачивается таблица здесь, один раз при загрузке.
 *
 * Значением по умолчанию становится самое частое значение поля — но только у поля, которое
 * есть у всех записей. Поле, которого у части записей нет вовсе (`turret`, `consumes`),
 * так и остаётся только у тех, у кого оно есть: отсутствие тоже смысл.
 *
 * Ключ с записями в файле называется `packed`, а не `blocks`: код, который по старой памяти
 * полезет в файл напрямую, упадёт сразу, а не прочитает блоки без половины полей.
 */

import blocksFile from '../data/block-specs.json' with {type: 'json'}
import unitsFile from '../data/unit-specs.json' with {type: 'json'}

import {expandSpecs} from './pack.js'

export {expandSpecs, packSpecs} from './pack.js'

/** Все блоки игры по имени: размер, здоровье, производство, правила постановки. */
export const BLOCK_SPECS = expandSpecs(blocksFile)

/** Все юниты игры по имени. */
export const UNIT_SPECS = expandSpecs(unitsFile)
